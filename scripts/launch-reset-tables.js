/**
 * What scripts/launch-reset.js does with every table, one entry per table.
 * The script refuses, in a dry run too, while the database holds a table that
 * is not listed here (one listed here that the database lacks is only
 * reported), and scripts/ci-check.js fails while a model's table is missing,
 * so a new migration's table has to be classified before the reset can run.
 *
 *   keep          every row stays exactly as it is
 *   keep-creator  only the creator's row stays (users: platform_role = 'creator',
 *                 exactly one); every other row is deleted
 *   wipe          every row is deleted (DELETE, children before parents)
 *   truncate      every row is deleted with TRUNCATE ... RESTRICT, before the
 *                 deletes (the wallet ledger refuses DELETE on its rows)
 *   decide        not clear which: kept as it is until it is moved to one of the
 *                 above, and --apply refuses while any table is still here
 *                 ({ action: 'decide', why }); none is left today
 *
 * The rule: the platform's own setup (what migrations seed and what the
 * console configures for every store) is kept; anything that belongs to a
 * store or to an account, the creator's sessions, codes and devices included,
 * goes. A kept row may not point at a row that goes (--apply refuses and lists
 * it), so a kept table with a user column (platform_settings.updated_by) must
 * name the creator or nobody when the reset runs.
 */

